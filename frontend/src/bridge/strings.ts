/** a string in the current language, with its {placeholders} filled */
export function bt(k: Key, v: Record<string, string | number> = {}): string {
  const s = (getLang() === 'fr' ? FR : EN)[k] ?? EN[k]
  return s.replace(/\{(\w+)\}/g, (_m, n: string) => String(v[n] ?? `{${n}}`))
}
