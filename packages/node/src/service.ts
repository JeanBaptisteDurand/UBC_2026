/** service.ts — "archive-node service install | uninstall": the agent started at boot
 *  (systemd on Linux; on macOS, the launchd equivalent is shown). The key is NEVER written into the unit: the
 *  service reads ~/.archive/node.json, or the file given by --key-file (only its path appears in the unit). */
import { existsSync, readFileSync, realpathSync, unlinkSync, writeFileSync } from "node:fs";
import { homedir, platform, userInfo } from "node:os";
import { dirname, join, resolve } from "node:path";
import { planUp, type UpFlags, type UpPlan } from "./agent";
import { archiveDir, tilde, writePrivateFile } from "./config";
import { DEFAULT_API, DEFAULT_IMAGE } from "./constants";
import { CliError } from "./errors";
import { lastLine, run } from "./exec";
import { ARROW, OK, WARN, bold, dim, out } from "./ui";

export const UNIT_NAME = "archive-node";
export const UNIT_PATH = `/etc/systemd/system/${UNIT_NAME}.service`;
export const LAUNCHD_LABEL = "io.archive.node";

/** the "up" options to replay at boot: never the key, only the (absolute) --key-file path */
export function upArgsFromPlan(p: UpPlan, f: UpFlags): string[] {
  const a = ["up", "--product", String(p.product), "--port", String(p.port)];
  if (p.image !== DEFAULT_IMAGE) a.push("--image", p.image);
  if (f.demo) a.push("--demo");
  if (p.publicUrl) a.push("--public-url", p.publicUrl);
  else if (p.tunnel) a.push("--tunnel");
  if (f.api || (process.env.ARCHIVE_API && p.api !== DEFAULT_API)) a.push("--api", p.api);
  if (f.keyFile?.trim()) a.push("--key-file", resolve(f.keyFile.trim()));
  return a;
}

/** ARCHIVE_KEY is not copied into the service: it would be readable in clear there */
const ENV_KEY_NOTE = "The ARCHIVE_KEY variable is not copied into the service (it would be readable in clear there): the service will read ~/.archive/node.json, or the file given with --key-file.";

/** an ExecStart= argument: in quotes, with systemd's escapes (\, ", %, $) */
export function systemdQuote(s: string): string {
  return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/%/g, "%%").replace(/\$/g, "$$$$")}"`;
}
const envQuote = (s: string): string => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/%/g, "%%")}"`;

export interface UnitSpec {
  user: string;
  home: string;
  path: string;
  archiveHome?: string;
  execStart: string[];
}

export function renderSystemdUnit(u: UnitSpec): string {
  return [
    "# Generated by “archive-node service install”: the ArcHive operator agent.",
    "# The operator key is not here: it stays in ~/.archive/node.json (mode 0600).",
    "[Unit]",
    "Description=ArcHive operator agent (archive-node)",
    "Wants=network-online.target",
    "After=network-online.target docker.service",
    "",
    "[Service]",
    "Type=simple",
    `User=${u.user}`,
    `Environment=${envQuote(`HOME=${u.home}`)}`,
    `Environment=${envQuote(`PATH=${u.path}`)}`,
    ...(u.archiveHome ? [`Environment=${envQuote(`ARCHIVE_HOME=${u.archiveHome}`)}`] : []),
    `ExecStart=${u.execStart.map(systemdQuote).join(" ")}`,
    "Restart=always",
    "RestartSec=10",
    "KillMode=mixed",
    "TimeoutStopSec=45",
    "",
    "[Install]",
    "WantedBy=multi-user.target",
    "",
  ].join("\n");
}

const xml = (s: string): string => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

export function renderLaunchdPlist(program: string[], env: Record<string, string>, log: string): string {
  return [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">`,
    `<plist version="1.0"><dict>`,
    `  <key>Label</key><string>${LAUNCHD_LABEL}</string>`,
    `  <key>ProgramArguments</key><array>`,
    ...program.map((a) => `    <string>${xml(a)}</string>`),
    `  </array>`,
    `  <key>EnvironmentVariables</key><dict>`,
    ...Object.entries(env).map(([k, v]) => `    <key>${xml(k)}</key><string>${xml(v)}</string>`),
    `  </dict>`,
    `  <key>RunAtLoad</key><true/>`,
    `  <key>KeepAlive</key><true/>`,
    `  <key>StandardOutPath</key><string>${xml(log)}</string>`,
    `  <key>StandardErrorPath</key><string>${xml(log)}</string>`,
    `</dict></plist>`,
  ].join("\n");
}

/** the service's PATH: the one here (docker, cloudflared) + node's folder */
function servicePath(): string {
  const parts = (process.env.PATH ?? "").split(":").filter(Boolean);
  const nodeDir = dirname(process.execPath);
  for (const d of [nodeDir, "/usr/local/sbin", "/usr/local/bin", "/usr/sbin", "/usr/bin", "/sbin", "/bin"]) if (!parts.includes(d)) parts.push(d);
  return parts.join(":");
}

/** a node path that survives updates (/usr/bin/node, /opt/homebrew/bin/node…) rather than /…/Cellar/node/25.2.1/bin/node */
function stableNodePath(): string {
  const real = (p: string): string | null => {
    try {
      return realpathSync(p);
    } catch {
      return null;
    }
  };
  const target = real(process.execPath);
  for (const dir of (process.env.PATH ?? "").split(":").filter(Boolean)) {
    const candidate = join(dir, "node");
    if (target && real(candidate) === target) return candidate;
  }
  return process.execPath;
}

/** another user's home folder (under sudo: the one who typed the command) */
function homeOf(user: string): string | null {
  try {
    for (const line of readFileSync("/etc/passwd", "utf8").split("\n")) {
      const f = line.split(":");
      if (f[0] === user && f[5]) return f[5];
    }
  } catch {
    /* no readable /etc/passwd */
  }
  return null;
}

function scriptPath(): string {
  const a = process.argv[1];
  if (!a) throw new CliError("Can't find the path of archive-node.");
  try {
    return realpathSync(a);
  } catch {
    return a;
  }
}

export async function serviceInstall(f: UpFlags): Promise<number> {
  const plan = planUp(f, { requireKey: false }); // the same checks as "up" (including the refusal of --key)
  const program = [stableNodePath(), scriptPath(), ...upArgsFromPlan(plan, f)];
  const os = platform();
  const keyFile = !!f.keyFile?.trim();
  const envKey = !keyFile && !!process.env.ARCHIVE_KEY?.trim();

  if (os === "darwin") {
    const log = join(archiveDir(), "archive-node.log");
    const plistPath = `~/Library/LaunchAgents/${LAUNCHD_LABEL}.plist`;
    out(`${bold("macOS")} has no systemd: the equivalent is a launchd agent. Save this in ${bold(plistPath)}:`);
    out();
    const env: Record<string, string> = { PATH: servicePath() };
    if (process.env.ARCHIVE_HOME?.trim()) env.ARCHIVE_HOME = process.env.ARCHIVE_HOME.trim();
    out(renderLaunchdPlist(program, env, log));
    out();
    out("Then load it (it starts at every login; Docker Desktop must be running):");
    out(`  launchctl bootstrap gui/$(id -u) ${plistPath}`);
    out(dim(`Stop: launchctl bootout gui/$(id -u)/${LAUNCHD_LABEL} · logs: tail -f ${tilde(log)}`));
    if (plan.keyWarning) out(`${WARN} ${plan.keyWarning}`);
    if (envKey) out(`${WARN} ${ENV_KEY_NOTE}`);
    if (!keyFile && !plan.cfg?.key) out(`${WARN} Machine not paired yet: run archive-node pair before loading the agent.`);
    return 0;
  }
  if (os !== "linux") throw new CliError(`Service not supported on ${os}: run archive-node up in a terminal.`);
  const sd = await run("systemctl", ["--version"], { timeoutMs: 5000 });
  if (sd.missing || sd.code !== 0) {
    throw new CliError("No systemd on this machine (systemctl not found): run archive-node up in a terminal, or in tmux/screen so it survives logging out.");
  }

  const isRoot = process.getuid?.() === 0;
  const sudoUser = isRoot && process.env.SUDO_USER && process.env.SUDO_USER !== "root" ? process.env.SUDO_USER : null;
  const user = sudoUser ?? userInfo().username;
  const home = sudoUser ? homeOf(sudoUser) ?? homedir() : homedir();
  const archiveHome = process.env.ARCHIVE_HOME?.trim() || undefined;
  const unit = renderSystemdUnit({ user, home, path: servicePath(), archiveHome, execStart: program });

  const cfgFile = join(archiveHome ?? join(home, ".archive"), "node.json");
  const warnings: string[] = [];
  if (plan.keyWarning) warnings.push(plan.keyWarning);
  if (envKey) warnings.push(ENV_KEY_NOTE);
  if (!keyFile && !existsSync(cfgFile)) warnings.push(`Machine not paired yet for ${user} (${cfgFile} missing): run archive-node pair, otherwise the service will stop right away.`);
  if (user !== "root") {
    const g = await run("id", ["-nG", user], { timeoutMs: 3000 });
    if (g.code === 0 && !g.stdout.split(/\s+/).includes("docker")) {
      warnings.push(`The user ${user} isn't in the docker group: sudo usermod -aG docker ${user} (otherwise the service can't start the enclave).`);
    }
  }

  if (!isRoot) {
    const local = join(archiveDir(), `${UNIT_NAME}.service`);
    writePrivateFile(local, unit);
    out(`systemd unit written to ${bold(tilde(local))} (runs as ${user}).`);
    out("Installing it needs root; run:");
    out(`  sudo install -m 644 ${local} ${UNIT_PATH}`);
    out("  sudo systemctl daemon-reload");
    out(`  sudo systemctl enable --now ${UNIT_NAME}`);
    out(dim(`Follow: journalctl -u ${UNIT_NAME} -f · stop: sudo systemctl stop ${UNIT_NAME}`));
    for (const w of warnings) out(`${WARN} ${w}`);
    return 0;
  }

  writeFileSync(UNIT_PATH, unit, { mode: 0o644 });
  for (const args of [["daemon-reload"], ["enable", UNIT_NAME], ["restart", UNIT_NAME]]) {
    const r = await run("systemctl", args, { timeoutMs: 60_000 });
    if (r.code !== 0) throw new CliError(`systemctl ${args.join(" ")} failed: ${lastLine(r.stderr) || `code ${r.code}`}`);
  }
  out(`${OK} Service ${bold(UNIT_NAME)} installed (${UNIT_PATH}), enabled at boot and started as ${user}.`);
  out(`${ARROW} Follow: journalctl -u ${UNIT_NAME} -f · status: archive-node status`);
  for (const w of warnings) out(`${WARN} ${w}`);
  return 0;
}

export async function serviceUninstall(): Promise<number> {
  const os = platform();
  if (os === "darwin") {
    out("On macOS, remove the launchd agent:");
    out(`  launchctl bootout gui/$(id -u)/${LAUNCHD_LABEL}`);
    out(`  rm ~/Library/LaunchAgents/${LAUNCHD_LABEL}.plist`);
    return 0;
  }
  if (os !== "linux") throw new CliError(`Service not supported on ${os}.`);
  if (process.getuid?.() !== 0) {
    out("This needs root; run:");
    out(`  sudo systemctl disable --now ${UNIT_NAME}`);
    out(`  sudo rm ${UNIT_PATH}`);
    out("  sudo systemctl daemon-reload");
    return 0;
  }
  if (!existsSync(UNIT_PATH)) {
    out(`No ${UNIT_NAME} service installed (${UNIT_PATH} missing).`);
    return 0;
  }
  await run("systemctl", ["disable", "--now", UNIT_NAME], { timeoutMs: 90_000 }); // the agent stops the enclave and tells the site
  unlinkSync(UNIT_PATH);
  await run("systemctl", ["daemon-reload"], { timeoutMs: 30_000 });
  out(`${OK} Service ${UNIT_NAME} stopped and removed.`);
  return 0;
}
